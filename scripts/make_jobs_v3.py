"""Write results/jobs_budget_v3.txt: the protocol-v3 regeneration queue for scripts/pqueue.py.

  python3 scripts/make_jobs_v3.py && python3 scripts/pqueue.py --jobs results/jobs_budget_v3.txt --budget 96 --max-jobs 40

Phases: archive v2 derived records -> freeze the long-budget plans -> per (group, seed) workers (sweep cells,
stepwise / online-EM cells, references for the new seeds 3-4) -> per-group finals (tuned-baseline selection over
all 5 seeds, untuned law curves, swept emission, track-specific baselines) -> isolated timing pass (exclusive,
CPU only) -> T12 fits, verdicts, figures.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = ".venv/bin/python -u"
SEEDS = range(5)
NEW_SEEDS = (3, 4)
CHUNKS = {"short": "0.25,0.5,1,2,3,5", "t10": "10", "t25": "25"}  # one worker per (group, seed, chunk)
TRACKS = {  # slug: (short, runner, gpu port, datasets, threads per worker, extra final stages)
    "gmm-ema": ("gmm", "tracks/gmm-ema/run_v2.py", "gmm",
                [f"{d}:{c}" for d in ("synthetic", "sift1m_pca64", "dinov2_pca64", "agnews_pca64") for c in ("diag", "full")],
                2, ()),
    "dictlearn-scaling": ("dl", "tracks/dictlearn-scaling/run_v2.py", "dictlearn", ["cifar_p8", "nmf_20ng", "cifar_p12"], 3,
                          ("sklearn",)),
    "lda-scaling": ("lda", "tracks/lda-scaling/run_v2.py", "lda", ["20ng", "enron", "nytimes"], 2, ("hoffman", "cosine-law")),
    "als-ema": ("als", "tracks/als-ema/run_v2.py", "als", ["ml1m", "ml10m"], 2, ()),
    "hmm-ema": ("hmm", "tracks/hmm-ema/run_v2.py", "hmm", ["synthetic", "brown_pos", "uci_har_vq"], 2, ()),
}
TIMING_WARMUP = {"gmm-ema": "synthetic", "dictlearn-scaling": "nmf_20ng", "lda-scaling": "20ng", "als-ema": "ml1m",
                 "hmm-ema": "uci_har_vq"}


def main():
    L = ["# Protocol v3 regeneration (core/budgets.py, PAPER_LOG.md §2): budgets 0.25 .. 25 epochs, 5 seeds.",
         "# Generated by scripts/make_jobs_v3.py; do not edit by hand.",
         "id=v3_archive threads=1 :: python3 scripts/archive_v3.py >> results/v3_archive.log 2>&1"]
    finals_all = []
    for slug, (sh, runner, port, dsets, thr, extra) in TRACKS.items():
        env = f"CLASSIC_ALGOS_GPU_PORTS={port}"
        L.append(f"# --- {slug}")
        L.append(f"id=plan_{sh} threads=1 needs=data after=v3_archive :: {env} {PY} {runner} --stage plan "
                 f">> results/{slug}/console_v3_plan.log 2>&1")
        for ds in dsets:
            name, cov = (ds.split(":") + [None])[:2]
            sel = f"--datasets {name}" + (f" --covs {cov}" if cov else "")
            tag = f"{sh}_{name}" + (f"_{cov}" if cov else "")
            log = f"results/{slug}/console_v3_{name}{'_' + cov if cov else ''}"
            sw, on = [], []
            for s in SEEDS:
                for ck, bud in CHUNKS.items():
                    benv = f"CLASSIC_ALGOS_BUDGETS={bud} {env}"
                    L.append(f"id=sw_{tag}_s{s}_{ck} threads={thr} needs=data after=plan_{sh} :: {benv} {PY} {runner} {sel} "
                             f"--stage sweep --seed-list {s} >> {log}_sweep{s}_{ck}.log 2>&1")
                    L.append(f"id=on_{tag}_s{s}_{ck} threads={thr} needs=data after=plan_{sh} :: CLASSIC_ALGOS_STEPWISE_CELLS_ONLY=1 "
                             f"{benv} {PY} {runner} {sel} --stage online --seed-list {s} >> {log}_online{s}_{ck}.log 2>&1")
                    sw.append(f"sw_{tag}_s{s}_{ck}")
                    on.append(f"on_{tag}_s{s}_{ck}")
            refs = []
            for s in NEW_SEEDS:
                L.append(f"id=ref_{tag}_s{s} threads={thr} needs=data after=v3_archive :: {env} {PY} {runner} {sel} "
                         f"--stage reference --seed-list {s} >> {log}_ref{s}.log 2>&1")
                refs.append(f"ref_{tag}_s{s}")
            L.append(f"id=fin_online_{tag} threads=1 needs=data after={','.join(on)} :: {env} {PY} {runner} {sel} "
                     f"--stage online --seeds 5 >> {log}_final.log 2>&1")
            L.append(f"id=fin_kmlaw_{tag} threads={thr} needs=data after=v3_archive :: {env} {PY} {runner} {sel} "
                     f"--stage kmlaw --seeds 5 >> {log}_kmlaw.log 2>&1")
            L.append(f"id=fin_emit_{tag} threads=1 needs=data after={','.join(sw)} :: {env} {PY} {runner} {sel} "
                     f"--stage emit --seeds 5 >> {log}_final.log 2>&1")
            finals_all += [f"fin_online_{tag}", f"fin_kmlaw_{tag}", f"fin_emit_{tag}", *refs]
            for st in extra:
                L.append(f"id=fin_{st}_{tag} threads={thr} needs=data after=v3_archive :: {env} {PY} {runner} {sel} "
                         f"--stage {st} --seeds 5 >> {log}_{st}.log 2>&1")
                finals_all.append(f"fin_{st}_{tag}")
    L.append("# --- isolated timing pass on the v3 budgets (alone, CPU only, 12 threads, 3 seeds; references kept)")
    prev = ",".join(finals_all)
    for slug, (sh, runner, _port, _d, _t, _e) in TRACKS.items():
        tim = "CLASSIC_ALGOS_RESULTS_DIR=results/_timing CLASSIC_ALGOS_DEVICE=cpu"
        L.append(f"id=time3_{sh} threads=12 needs=data exclusive after={prev} :: "
                 f"CLASSIC_ALGOS_RESULTS_DIR=/tmp/warmup_{sh} CLASSIC_ALGOS_DEVICE=cpu {PY} {runner} "
                 f"--datasets {TIMING_WARMUP[slug]} --stage reference --seeds 1 >> results/timing_{sh}_v3.log 2>&1; "
                 f"{tim} {PY} {runner} --stage kmlaw >> results/timing_{sh}_v3.log 2>&1 && "
                 f"{tim} {PY} scripts/timing_swept.py {slug} >> results/timing_{sh}_v3.log 2>&1")
        prev = f"time3_{sh}"
    L.append("id=v3_evaluate threads=4 barrier :: .venv/bin/python tracks/universal-scaling-law/fit_v2.py "
             ">> results/universal-scaling-law/console.log 2>&1; .venv/bin/python tracks/universal-scaling-law/refit_coords.py "
             "> results/universal-scaling-law/refit_coords.log 2>&1; .venv/bin/python scripts/evaluate.py "
             "> results/evaluate_all.log 2>&1 && .venv/bin/python scripts/make_figures.py >> results/evaluate_all.log 2>&1")
    out = ROOT / "results" / "jobs_budget_v3.txt"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {sum(1 for x in L if x.startswith('id='))} jobs")


if __name__ == "__main__":
    main()
